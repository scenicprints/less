"""Run this to regenerate the SVGs, the Android drawables and the index. The icons are in set.py.

Each icon is an optional tile colour and a list of marks. A mark is a path with a fill, or a stroke, or
both. Rectangles and circles are written as paths so that the SVG and the Android drawable are
the same drawing; nothing here is used that Android's vector format cannot draw.
"""
import json
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SVG_DIR = os.path.join(HERE, "svg")
DRAWABLE_DIR = os.path.join(HERE, "..", "app", "src", "main", "res", "drawable")
ASSETS_DIR = os.path.join(HERE, "..", "app", "src", "main", "assets")

WHITE = "#F6F2EA"
INK = "#1B1B19"
STROKE = 4

# Google's four, flattened. Used by several marks so they agree with each other.
BLUE = "#4285F4"
RED = "#DB4437"
YELLOW = "#F4B400"
GREEN = "#0F9D58"


def rect(x, y, w, h, r=0):
    """A rectangle with optional corner radius, as path data."""
    if r == 0:
        return f"M{x} {y}h{w}v{h}h{-w}z"
    return (
        f"M{x + r} {y}h{w - 2 * r}a{r} {r} 0 0 1 {r} {r}v{h - 2 * r}a{r} {r} 0 0 1 {-r} {r}"
        f"h{-(w - 2 * r)}a{r} {r} 0 0 1 {-r} {-r}v{-(h - 2 * r)}a{r} {r} 0 0 1 {r} {-r}z"
    )


def circle(cx, cy, r):
    return f"M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0z"


def arc(cx, cy, r, start, end):
    """An open arc from angle start to end, degrees, clockwise on screen."""
    s, e = math.radians(start), math.radians(end)
    x1, y1 = cx + r * math.cos(s), cy + r * math.sin(s)
    x2, y2 = cx + r * math.cos(e), cy + r * math.sin(e)
    large = 1 if (end - start) % 360 > 180 else 0
    return f"M{x1:.2f} {y1:.2f}A{r} {r} 0 {large} 1 {x2:.2f} {y2:.2f}"


def wedge(cx, cy, r, start, end):
    """A filled sector, for rings made of coloured thirds and quarters."""
    s, e = math.radians(start), math.radians(end)
    x1, y1 = cx + r * math.cos(s), cy + r * math.sin(s)
    x2, y2 = cx + r * math.cos(e), cy + r * math.sin(e)
    large = 1 if (end - start) % 360 > 180 else 0
    return f"M{cx} {cy}L{x1:.2f} {y1:.2f}A{r} {r} 0 {large} 1 {x2:.2f} {y2:.2f}z"


def gear(cx, cy, r_out, r_in, teeth):
    pts = []
    for i in range(teeth * 2):
        a = math.pi * i / teeth
        r = r_out if i % 2 == 0 else r_in
        for da in (-0.14, 0.14):
            pts.append((cx + r * math.cos(a + da), cy + r * math.sin(a + da)))
    return "M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + "z"


def tile(colour):
    return rect(0, 0, 56, 56, 14), colour


def fill(d, colour):
    return {"d": d, "fill": colour}


def stroke(d, colour, width=STROKE):
    return {"d": d, "stroke": colour, "width": width}


ICONS = {}


def icon(package, name, tile_colour, *marks):
    ICONS[package] = {"name": name, "tile": tile_colour, "marks": list(marks)}


# ------------------------------------------------------------- the writers

def svg_of(entry):
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 56 56" width="56" height="56">']
    if entry["tile"]:
        d, colour = tile(entry["tile"])
        parts.append(f'  <path d="{d}" fill="{colour}"/>')
    for m in entry["marks"]:
        attrs = [f'd="{m["d"]}"']
        attrs.append(f'fill="{m["fill"]}"' if "fill" in m else 'fill="none"')
        if "stroke" in m:
            attrs.append(f'stroke="{m["stroke"]}" stroke-width="{m["width"]}" stroke-linecap="round" stroke-linejoin="round"')
        parts.append("  <path " + " ".join(attrs) + "/>")
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def drawable_of(entry):
    parts = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by icons/make.py. Edit the icon there, not here. -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="56dp"',
        '    android:height="56dp"',
        '    android:viewportWidth="56"',
        '    android:viewportHeight="56">',
    ]
    if entry["tile"]:
        d, colour = tile(entry["tile"])
        parts.append(f'    <path android:pathData="{d}" android:fillColor="{colour}" />')
    for m in entry["marks"]:
        attrs = [f'android:pathData="{m["d"]}"']
        if "fill" in m:
            attrs.append(f'android:fillColor="{m["fill"]}"')
        if "stroke" in m:
            attrs.append(f'android:strokeColor="{m["stroke"]}"')
            attrs.append(f'android:strokeWidth="{m["width"]}"')
            attrs.append('android:strokeLineCap="round"')
            attrs.append('android:strokeLineJoin="round"')
        parts.append("    <path " + " ".join(attrs) + " />")
    parts.append("</vector>")
    return "\n".join(parts) + "\n"


def main():
    # set.py imports the helpers from "make"; when this file runs as a script that name must
    # point at this very module, or the icons would register in a second copy of it.
    import sys
    sys.modules.setdefault("make", sys.modules[__name__])
    import set  # noqa: F401  the icons register themselves on import
    os.makedirs(SVG_DIR, exist_ok=True)
    os.makedirs(DRAWABLE_DIR, exist_ok=True)
    os.makedirs(ASSETS_DIR, exist_ok=True)
    # Old outputs go, so a renamed or removed icon leaves nothing behind.
    for d, pat in ((SVG_DIR, r".*\.svg"), (DRAWABLE_DIR, r"ic_.*\.xml")):
        for f in os.listdir(d):
            if re.fullmatch(pat, f):
                os.remove(os.path.join(d, f))
    index = {}
    for package, entry in ICONS.items():
        name = entry["name"]
        assert re.fullmatch(r"[a-z][a-z0-9_]*", name), name
        with open(os.path.join(SVG_DIR, f"{package}.svg"), "w", encoding="utf-8", newline="\n") as f:
            f.write(svg_of(entry))
        with open(os.path.join(DRAWABLE_DIR, f"ic_{name}.xml"), "w", encoding="utf-8", newline="\n") as f:
            f.write(drawable_of(entry))
        index[package] = f"ic_{name}"
    with open(os.path.join(ASSETS_DIR, "icons.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(index, f, indent=2, sort_keys=True)
        f.write("\n")
    print(f"{len(index)} icons written")


if __name__ == "__main__":
    main()
